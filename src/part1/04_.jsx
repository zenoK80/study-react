// -------------------------------------------------------------------------------------
// [미션] Props로 인사 메시지 바꾸기
// -------------------------------------------------------------------------------------
// Greeting 컴포넌트가 name props를 전달받는다.
// 전달받은 이름을 jsx 안에서 출력한다.
// name을 전달하지 않으면 기본값 "Guest"를 사용한다.
// -------------------------------------------------------------------------------------
// 배우고자 하는 것:
// - props는 부모가 자식 컴포넌트에 전달하는 데이터다.
// - props는 컴포넌트 함수의 첫 번째 매개변수로 전달된다.
// - 구조 분해 할당으로 필요한 props만 꺼낼 수 있다.
// - props는 읽기 전용이므로 자식 컴포넌트가 직접 수정하면 안 된다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [1] Greeting 컴포넌트
// -------------------------------------------------------------------------------------
// - { name }은 props 객체에서 name 속성을 꺼내는 구조 분해 할당이다.
// - name = "Guest"는 name이 전달되지 않았을 때 사용할 기본값이다.
// -------------------------------------------------------------------------------------
function Greeting({name = "Guest"}){
  return <h2>Hello, {name}!</h2>;
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [2] 대표 컴포넌트
// -------------------------------------------------------------------------------------
export default function GreetingPractice(){
  return(
    <section>
      <Greeting name="Yongsu"/>
    </section>
  )
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [마무리 정리]
// -------------------------------------------------------------------------------------
// - props는 부모 컴포넌트가 자식 컴포넌트에 전달하는 데이터다.
// - JSX의 문자열 props는 name="Yongsu"처럼 전달한다.
// - JSX의 {} 안에는 JavaScript 표현식을 작성할 수 있다.
// - props는 읽기 전용이며 자식 컴포넌트에서 직접 수정하지 않는다.
// -------------------------------------------------------------------------------------
