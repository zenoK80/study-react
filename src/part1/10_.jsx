// 내용:
// - 버튼을 클릭할 때마다 켜짐/꺼짐 상태를 변경한다.
// - 현재 상태에 따라 화면의 문구와 버튼 글자를 변경한다.
//
// 배우고자 하는 것:
// - onClick 이벤트
// - useState로 boolean 상태 관리
// - 이전 상태를 반대로 변경하는 방법
// - 삼항 연산자를 사용한 조건부 렌더링
// -------------------------------------------------------------------------------------
import { useState } from "react";

// -------------------------------------------------------------------------------------
// [1] ToggleButton
// -------------------------------------------------------------------------------------
export default function ToggleButton(){
  const [isOn, setIsOn] = useState(false);

  function handleToggle(){
    setIsOn((p_isOn) => !p_isOn);
  }

  return(
    <section>
      <h2>전원 상태</h2>
      <p>{isOn ? "켜짐" : "꺼짐"}</p>
      <button type="button" onClick={handleToggle}>{isOn ? "끄기" : "켜기"}</button>
    </section>
  )
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [동작 흐름]
// -------------------------------------------------------------------------------------
// 1. ToggleButton 컴포넌트가 처음 실행된다.
// 2. useState(false)로 isOn의 초기값이 false가 된다.
// 3. 화면에 "꺼짐 상태입니다."와 "켜기" 버튼이 출력된다.
// 4. 사용자가 버튼을 클릭하면 handleToggle 함수가 실행된다.
// 5. setIsOn이 이전 상태를 반대값으로 변경한다.
// 6. React가 ToggleButton 컴포넌트를 다시 실행한다.
// 7. 변경된 isOn 값에 따라 문구와 버튼 글자가 바뀐다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [용어 정리]
// -------------------------------------------------------------------------------------
// - boolean: true 또는 false만 가지는 데이터 타입
// - onClick: 사용자가 요소를 클릭했을 때 실행할 함수를 지정하는 이벤트
// - !isOn: 현재 boolean 값을 반대로 바꾼 값
// - 조건부 렌더링: 조건에 따라 서로 다른 화면을 출력하는 방식
// - 삼항 연산자: 조건 ? 참일 때 값 : 거짓일 때 값
// - p_isOn: 상태가 변경되기 전의 최신 isOn 값
// - 함수형 업데이트: 이전 상태를 전달받아 새로운 상태를 계산하는 방식
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [마무리 정리]
// -------------------------------------------------------------------------------------
// - 이벤트가 발생하면 이벤트 핸들러가 실행된다.
// - setIsOn으로 state를 변경하면 컴포넌트가 다시 렌더링된다.
// - boolean 상태는 ! 연산자를 사용해 true와 false를 전환할 수 있다.
// - 삼항 연산자를 사용하면 state에 따라 다른 UI를 출력할 수 있다.
// - React에서는 DOM을 직접 수정하지 않고 state를 변경해 화면을 갱신한다.
// -------------------------------------------------------------------------------------
