// -------------------------------------------------------------------------------------
// 내용:
// - 과일 항목을 클릭하면 이름과 인덱스를 콘솔에 출력한다.
// - React가 전달하는 SyntheticEvent 객체를 확인한다.
//
// 배우고자 하는 것:
// - onClick의 camelCase 표기
// - 이벤트 핸들러에 함수 전달
// - map의 item과 index
// - SyntheticEvent 객체
// -------------------------------------------------------------------------------------
// SyntheticEvent 객체 : 브라우저 이벤트를 React가 감싸서 제공하는 이벤트 객체
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [1] FruitList 대표 컴포넌트
// -------------------------------------------------------------------------------------
// [이벤트 핸들러]
// -----------------------------------------------------------------------------------
// - item: 클릭한 과일 이름
// - index: 클릭한 과일의 배열 인덱스
// - event: React가 전달한 이벤트 객체
// -----------------------------------------------------------------------------------
const fruits = ["사과","바나나","체리"];
export default function FruitList(){
  function handleClick(item,index,event){
    console.log('item:클릭된 항목',item);
    console.log("index",index);
    console.log('SyntheticEvent객체',event);
  }
  return(
    <ul>
      {fruits.map((item,index)=>(
        <li key={item} onClick={event => handleClick(item, index, event)}>{item}</li>
      ))}
    </ul>
  )
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [동작 흐름]
// -------------------------------------------------------------------------------------
// fruits.map()이 과일 배열을 순회한다.
// 각 과일을 li JSX로 변환한다.
// 사용자가 li를 클릭한다.
// React가 event 객체를 화살표 함수에 전달한다.
// handleClick에 item, index, event를 전달한다.
// 콘솔에 과일 이름, 인덱스, 이벤트 객체가 출력된다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [용어 정리]
// -------------------------------------------------------------------------------------
// - event: 이벤트가 발생했을 때 React가 전달하는 실제 데이터 객체
// - event.target: 이벤트가 실제로 발생한 요소
// - event.currentTarget: 이벤트 핸들러가 연결된 요소
// - event.type: 발생한 이벤트 종류, 예: "click"
// - SyntheticEvent: 브라우저 이벤트를 React가 감싸서 제공하는 이벤트 객체
// - map(item, index): item은 현재 요소, index는 현재 요소의 배열 위치
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [마무리 정리]
// -------------------------------------------------------------------------------------
// - React 이벤트 속성은 onclick이 아니라 onClick처럼 camelCase로 작성한다.
// - onClick에는 실행 결과가 아니라 실행할 함수를 전달한다.
// - 추가 값을 전달하려면 화살표 함수로 이벤트 핸들러를 감싼다.
// - key는 이벤트와 별개로 React가 리스트 항목을 구별할 때 사용한다.
// -------------------------------------------------------------------------------------
