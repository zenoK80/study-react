//----------------------------------------------------------------------------------
// [1] Greeting 부품 컴포넌트 선언 및 Props 구조 분해 할당
// - 역할: 부모 컴포넌트에서 전달받은 name 속성을 받아옴
// - 원리: 매개변수 위치에서 ({ name })으로 바로 객체를 해체하여 props.name 생략
//----------------------------------------------------------------------------------
function Greeting({ name }) {

  //--------------------------------------------------------------------------------
  // [2] 동적 UI 반환 (return)
  // - 역할: 전달받은 name 변수를 JSX 내부에 동적으로 바인딩하여 출력
  // - 원리: JSX 중괄호({ }) 문법을 사용해 자바스크립트 변수 값을 HTML 태그 안에 표현
  //--------------------------------------------------------------------------------
  return (
    <div className="alert alert-success">
      <span className="text-xl font-bold">Hello, {name}!</span>
    </div>
  );
}
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [3] GreetingPractice 실행용 컴포넌트
// - 역할: Greeting 컴포넌트에 실제 name props를 넘겨서 화면에 보여줌
// - 원리: 학습 사이트는 <LessonComponent />만 실행하므로, 파일 내부에서 예시 props를 직접 전달
//----------------------------------------------------------------------------------
export default function GreetingPractice() {
  return (
    <div className="space-y-3">
      <Greeting name="React Learner" />
      <Greeting name="Codex Study" />
    </div>
  );
}
