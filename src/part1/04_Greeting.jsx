// [핵심 개념]
// 1. Props: 부모가 자식에게 넘겨주는 읽기 전용(Read-only) 데이터
// 2. 구조 분해: ({ name }) 처럼 매개변수에서 바로 뜯어서 'props.name' 대신 'name' 사용
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [1] Greeting 컴포넌트 선언 및 Props 구조 분해 할당
// - 역할: 부모 컴포넌트에서 전달받은 name 속성을 받아옴
// - 원리: 매개변수 위치에서 ({ name })으로 바로 객체를 해체하여 props.name 생략
//----------------------------------------------------------------------------------
function Greeting({ name }) {

  //--------------------------------------------------------------------------------
  // [2] 동적 UI 반환 (return)
  // - 역할: 전달받은 name 변수를 JSX 내부에 동적으로 바인딩하여 출력
  // - 원리: JSX 중괄호({ }) 문법을 사용해 자바스크립트 변수 값을 HTML 태그 안에 표현
  //--------------------------------------------------------------------------------
  return <h1>Hello, {name}!</h1>;
}
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [3] Greeting 컴포넌트 기본 내보내기 (export default)
// - 역할: 이 파일의 대표 컴포넌트로 내보내어 App.jsx 등 다른 파일에서 불러올 수 있게 함
// - 원리: export default 구문으로 파일당 하나의 기본 모듈 추출
//----------------------------------------------------------------------------------
export default Greeting;
//----------------------------------------------------------------------------------
