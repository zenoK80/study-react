// [학습목표] 변경된 데이터만 선택적으로 다시 그리는 가상 DOM 동작 이해
//----------------------------------------------------------------------------------

import React, { useState, useEffect } from "react";

//----------------------------------------------------------------------------------
// [핵심 개념]
// 1. useState: 상태(State)가 바뀔 때마다 컴포넌트 함수를 재실행(Re-render)함
// 2. Diffing (비교): 이전 Virtual DOM과 새 Virtual DOM을 비교해 바뀐 부분만 포착
// 3. 부분 업데이트: 화면 전체를 다시 그리지 않고 바뀐 수치 텍스트만 실제 DOM에 반영
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [1] ReactRenderingProcess 메인 컴포넌트 선언 및 내보내기
// - 역할: Virtual DOM의 부분 업데이트 동작 과정을 보여주는 실습 컴포넌트
// - 원리: export default 구문으로 컴포넌트를 기본 모듈로 내보냄
//----------------------------------------------------------------------------------
export default function ReactRenderingProcess() {

  //--------------------------------------------------------------------------------
  // [2] useState 상태(State) 선언
  // - 역할: 타이머 숫자를 저장하고 관리하는 'count' 상태값 생성
  // - 원리: setCount 함수로 값을 변경하면 리액트가 화면을 다시 그려야 함을 감지함
  //--------------------------------------------------------------------------------
  const [count, setCount] = useState(0);

  //--------------------------------------------------------------------------------
  // [3] useEffect 부수 효과(Side Effect) 처리
  // - 역할: 컴포넌트가 마운트될 때 1초마다 count를 1씩 증가시키는 타이머 실행
  // - 원리: cleanup 함수(clearInterval)를 반환하여 컴포넌트 종료 시 메모리 누수를 방지
  //--------------------------------------------------------------------------------
  useEffect(() => {
    const timer = setInterval(() => setCount((prev) => prev + 1), 1000);
    return () => clearInterval(timer);
  }, []);

  //--------------------------------------------------------------------------------
  // [4] JSX 반환 및 Virtual DOM 업데이트 관찰 (return)
  // - 역할: {count} 상태를 화면에 바인딩하여 출력
  // - 원리: count가 변경되어도 리액트 Diffing 알고리즘에 의해 <h1> 내부 숫자만 실제 DOM에 교체됨
  //--------------------------------------------------------------------------------
  return (
    <div className="space-y-4">
      <div>
        <h2 className="text-2xl font-bold">Virtual DOM 부분 업데이트 실험</h2>
        <p className="opacity-70 mt-1">count 상태가 바뀔 때 숫자 부분만 다시 렌더링되는지 확인합니다.</p>
      </div>

      <div className="stats shadow bg-base-200">
        <div className="stat">
          <div className="stat-title">Count</div>
          <div className="stat-value text-primary">{count}</div>
          <div className="stat-desc">1초마다 자동 증가</div>
        </div>
      </div>
    </div>
  );
}
