// -------------------------------------------------------------------------------------
// [03 나만의 첫 함수형 컴포넌트 만들기]
// -------------------------------------------------------------------------------------
// - Hello 함수형 컴포넌트 만들기
// - JSX를 반환하여 화면에 "Hello, React!"를 출력한다.

// 배우고자 하는 것
// - 함수형 컴포넌트는 JSX를 반환하는 Javascript 함수다.
// - 컴포넌트 이름은 반드시 대문자로 시작한다.
// - return으로 반환한 JSX가 화면에 렌더링된다.
// - 컴포넌트가 반환하는 최상위 요소는 하나여야 한다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [1] Hello Component
// - 대문자로 시작해야 React가 HTML 태그가 아닌 컴포넌트로 인식한다.
// - export default는 이 파일의 대표 컴포넌트로 내보낸다는 뜻이다.
// -------------------------------------------------------------------------------------
export default function Hello(){
  return(<h2>Hello, React</h2>);
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [동작 흐름]
// -------------------------------------------------------------------------------------
// App.jsx가 현재 주소에 해당하는 03_.jsx 파일을 불러온다.
// 이 파일의 export default인 Hello 컴포넌트를 가져온다.
// React가 Hello 함수를 실행한다.
// Hello 함수가 <h2>Hello, React!</h2> JSX를 반환한다.
// 반환된 JSX가 브라우저 화면에 출력된다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [마무리 정리]
// -------------------------------------------------------------------------------------
// - 함수형 컴포넌트는 JSX를 반환하는 함수다.
// - 컴포넌트 이름은 대문자로 시작해야 한다.
// - JSX는 화면에 표시할 UI 구조를 작성하는 문법이다.
// - export default로 내보낸 컴포넌트를 다른 파일에서 가져올 수 있다.
// - ReactDOM.createRoot()는 main.jsx에서 이미 실행되므로 실습 파일마다 작성하지 않는다.
// -------------------------------------------------------------------------------------


