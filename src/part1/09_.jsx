// -------------------------------------------------------------------------------------
// [미션] State의 힘 느껴보기
// -------------------------------------------------------------------------------------
// 내용:
// - 버튼을 클릭하면 화면의 숫자가 1씩 증가한다.
// - useState로 화면에 영향을 주는 값을 기억한다.
// - state가 변경되면 컴포넌트가 다시 렌더링되는 것을 확인한다.
//
// 배우고자 하는 것:
// - useState
// - state와 일반 변수의 차이
// - 이벤트와 상태 변경
// - 상태 변경에 따른 리렌더링
// -------------------------------------------------------------------------------------
import {useState} from "react";

// -------------------------------------------------------------------------------------
// [1]
// -------------------------------------------------------------------------------------
export default function Counter(){
  const [count,setCount]=useState(0);
  function handleIncrease(){
    setCount(count+1);
  }

  return(
    <section>
      <h2>State 카운터</h2>
      <p>현재 숫자: {count}</p>
      <button onClick={handleIncrease}>숫자 증가</button>
    </section>
  );
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [동작 흐름]
// -------------------------------------------------------------------------------------
// Counter 컴포넌트가 처음 실행된다.
// useState(0)으로 count의 초기값이 0이 된다.
// 화면에 현재 숫자 0이 출력된다.
// 사용자가 숫자 증가 버튼을 클릭한다.
// handleIncrease 함수가 실행된다.
// setCount(count + 1)이 새로운 상태값을 저장한다.
// React가 Counter 컴포넌트를 다시 실행한다.
// 변경된 count 값이 화면에 출력된다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [일반 변수와 state의 차이]
// -------------------------------------------------------------------------------------
// 일반 변수:
// - 값이 바뀌어도 React는 화면을 다시 그려야 하는지 알 수 없다.
// state:
// - setCount로 값을 변경하면 React가 컴포넌트를 다시 렌더링한다.
// - 변경된 값이 화면에 자동으로 반영된다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [용어 정리]
// -------------------------------------------------------------------------------------
// - state: 컴포넌트가 기억하며 화면에 영향을 주는 데이터
// - useState(): 함수형 컴포넌트에서 state를 만드는 React Hook
// - setCount(): count 상태를 변경하고 리렌더링을 요청하는 함수
// - 렌더링: React가 컴포넌트 함수를 실행하여 화면 구조를 계산하는 것
// - 리렌더링: state가 변경되어 컴포넌트 함수를 다시 실행하는 것

// - onClick={handleIncrease}:
//   handleIncrease를 실행하지 않고 함수 자체를 React에 전달한다.
//   클릭이 발생하면 React가 handleIncrease 함수를 실행한다.
//   별도로 전달할 인자가 없으므로 화살표 함수로 감쌀 필요가 없다.

// - onClick={handleIncrease()}:
//   handleIncrease 뒤의 ()는 함수를 지금 실행하라는 뜻이다.
//   클릭할 때가 아니라 컴포넌트가 렌더링될 때 즉시 실행되므로 잘못된 방식이다.

// - onClick={() => handleIncrease()}:
//   () =>는 매개변수가 없는 새로운 화살표 함수를 만든다.
//   렌더링할 때는 함수만 전달하고, 클릭하면 함수 안의 handleIncrease()를 실행한다.
//   현재 예제에서는 별도 인자가 없으므로 onClick={handleIncrease}가 더 간단하다.

// - 화살표 함수로 감싸는 경우:
//   이벤트 핸들러에 별도의 값을 전달해야 할 때 사용한다.
//   예: onClick={() => handleDelete(item.id)}

// - event까지 전달하는 경우:
//   React가 화살표 함수의 첫 번째 매개변수로 이벤트 객체를 전달한다.
//   예: onClick={event => handleClick(item, index, event)}

// - ()의 역할 차이:
//   handleIncrease()의 ()는 함수를 실행하는 호출 문법이다.
//   () => handleIncrease()의 앞쪽 ()는 화살표 함수의 매개변수 자리다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [마무리 정리]
// -------------------------------------------------------------------------------------
// - useState는 컴포넌트가 값을 기억할 수 있게 한다.
// - setCount로 state를 변경하면 React가 화면을 다시 그린다.
// - 개발자는 DOM을 직접 수정하지 않고 state만 변경한다.
// - React의 UI는 state에 따라 결정된다.
// -------------------------------------------------------------------------------------
