//----------------------------------------------------------------------------------
// [핵심 개념]
// 1. 컴포넌트 합성: 작은 부품 컴포넌트(Emoji, Title, UserInfo)를 조립해 큰 컴포넌트 완성
// 2. Props 전달: 상위(ProfileHeader)가 받은 데이터를 하위 자식들에게 재분배
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [1] Emoji 부품 컴포넌트
// - 역할: symbol 전달값을 받아 이모지 기호를 <span> 태그로 출력
// - 원리: ({ symbol }) 구조 분해 할당으로 props 객체에서 바로 추출
//----------------------------------------------------------------------------------
function Emoji({ symbol }) {
  return <span>{symbol}</span>;
}
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [2] Title 부품 컴포넌트
// - 역할: 사용자 이름을 전달받아 환영 메시지 헤딩(h2) 출력
// - 원리: 상위 컴포넌트에서 넘어온 name props를 받아 JSX 중괄호 표현식에 바인딩
//----------------------------------------------------------------------------------
function Title({ name }) {
  return <h2>Welcome, {name}!</h2>;
}
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [3] UserInfo 부품 컴포넌트
// - 역할: 나이(age)와 국가(country) 정보를 전달받아 한 줄 문장으로 출력
// - 원리: 다중 props 인자를 ({ age, country }) 형태로 한 번에 구조 분해하여 사용
//----------------------------------------------------------------------------------
function UserInfo({ age, country }) {
  return <p>Age: {age} | Country: {country}</p>;
}
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [4] ProfileHeader 상위 합성 컴포넌트
// - 역할: 자식 컴포넌트들(Emoji, Title, UserInfo)을 조립하여 프로필 헤더 레이아웃 완성
// - 원리: 외부에서 받은 props(name, age, country)를 하위 자식 컴포넌트들에게 다시 분배 전달
//----------------------------------------------------------------------------------
function ProfileHeader({ name, age, country }) {
  return (
    <header>
      <Emoji symbol="🧑‍💻" />
      <Title name={name} />
      <UserInfo age={age} country={country} />
    </header>
  );
}
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [5] ProfileHeader 컴포넌트 내보내기
// - 역할: 완제품 형태의 ProfileHeader를 메인 모듈로 내보냄
// - 원리: export default 구문으로 타 파일(App.jsx)에서 쉽게 불러와 사용할 수 있게 함
//----------------------------------------------------------------------------------
export default ProfileHeader;
//----------------------------------------------------------------------------------
