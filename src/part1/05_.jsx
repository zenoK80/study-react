// 내용:
// - 작은 컴포넌트를 여러 개 만든다.
// - props를 구조 분해 할당으로 전달받는다.
// - 작은 컴포넌트를 조합하여 ProfileHeader를 만든다.
//
// 배우고자 하는 것:
// - 컴포넌트 합성
// - props 구조 분해 할당
// - 부모에서 자식으로 데이터 전달
// - 하위 컴포넌트 재사용
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [1]
// -------------------------------------------------------------------------------------
function Emoji(){
  return <div aria-label="개발자">🧑‍💻</div>;
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [2]
// -------------------------------------------------------------------------------------
function Title({name}){
  return <h2>Welcome, {name}!</h2>;
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [3] UserInfo 컴포넌트
// -------------------------------------------------------------------------------------
// - age는 숫자, country는 문자열로 전달받는다.
// -------------------------------------------------------------------------------------
function UserInfo({ age, country }){
  return (
    <div>
      <p>Age: {age}</p>
      <p>Country: {country}</p>
    </div>
  );
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [4] ProfileHeader 대표 컴포넌트
// -------------------------------------------------------------------------------------
// - 여러 하위 컴포넌트를 하나의 컴포넌트로 조합한다.
// - 숫자 props는 age={20}처럼 {} 안에 작성한다.
// -------------------------------------------------------------------------------------
export default function ProfileHeader(){
  return (
    <header>
      <Emoji />
      <Title name="Yongsu" />
      <UserInfo age={20} country="Korea" />
    </header>
  );
}
// -------------------------------------------------------------------------------------

