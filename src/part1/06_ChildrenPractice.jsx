//----------------------------------------------------------------------------------
// [핵심 개념]
// 1. children: 태그 사이의 내용물(<p>...</p>)을 받아오는 특별한 Props
// 2. 단방향 흐름: 데이터는 무조건 상위 -> 하위(App -> Profile -> Card)로 이동
// 3. 래퍼 패턴: 공통 틀(Card) 안에 내용만 바꿔 재사용하는 구조
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [1] Card 컴포넌트 (래퍼/틀)
// - 역할: 내용물(children)을 감싸서 렌더링하는 박스 역할
// - 원리: ({ children })으로 태그 사이 요소들을 쏙 받아옴
//----------------------------------------------------------------------------------
function Card({ children }) {
  return (
    <div>
      {children}
    </div>
  );
}
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [2] Profile 컴포넌트 (합성)
// - 역할: 부모의 name과 children을 받아 Card 틀 안에 배치
// - 원리: App에서 넘어온 데이터를 자식(Card)에게 전달 (단방향 흐름)
//----------------------------------------------------------------------------------
function Profile({ name, children }) {
  return (
    <Card>
      <h3>[Profile]</h3>
      <p>Name: {name}</p>
      {children}
    </Card>
  );
}
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [3] 컴포넌트 내보내기
// - 원리: export default로 파일당 1개 대표 컴포넌트 추출
//----------------------------------------------------------------------------------
export default Profile;
//----------------------------------------------------------------------------------
