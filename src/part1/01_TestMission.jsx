//----------------------------------------------------------------------------------

import React from 'react';

//----------------------------------------------------------------------------------
// [핵심 개념]
// 1. JSX: 자바스크립트 안에서 HTML처럼 쓰는 확장 문법
// 2. Babel: JSX 구문을 React.createElement() 함수 호출로 번역해주는 트랜스파일러
// 3. Virtual DOM: 두 방식 모두 결과적으로 동일한 리액트 엘리먼트 객체(가상 DOM) 생성
//----------------------------------------------------------------------------------

//----------------------------------------------------------------------------------
// [1] TestMission 함수형 컴포넌트 선언 및 내보내기
// - 역할: JSX 방식과 React.createElement 방식의 결과물을 비교 렌더링하는 메인 컴포넌트
// - 원리: export default를 앞에 붙여 선언과 동시에 기본 모듈로 내보냄
//----------------------------------------------------------------------------------
export default function TestMission() {

  //--------------------------------------------------------------------------------
  // [2] JSX 방식과 React.createElement 방식을 통한 리액트 엘리먼트 생성
  // - 역할: 동일한 UI(<h1>Hello JSX!</h1>)를 서로 다른 작성 방식으로 생성함
  // - 원리: el1의 JSX 구문은 빌드 시 Babel에 의해 el2와 같은 형태로 자동 변환됨
  //--------------------------------------------------------------------------------
  const el1 = <h1>Hello JSX!</h1>;
  const el2 = React.createElement("h1", null, "Hello JSX!");

  //--------------------------------------------------------------------------------
  // [3] 개발자 도구(F12) 콘솔 출력
  // - 역할: 두 변수(el1, el2)의 내부 구조를 콘솔창에서 확인
  // - 원리: 두 변수 모두 $$typeof, type, props를 가진 동일한 Virtual DOM 객체임을 증명
  //--------------------------------------------------------------------------------
  console.log("JSX 변환 결과:", el1);
  console.log("createElement 결과:", el2);

  //--------------------------------------------------------------------------------
  // [4] JSX 화면 렌더링 반환 (return)
  // - 역할: 생성된 가상 DOM 객체 변수들을 화면에 배치하여 출력
  // - 원리: JSX 중괄호({el1}, {el2})를 사용해 자바스크립트 객체 변수를 HTML 내에 바인딩
  //--------------------------------------------------------------------------------
  return (
    <div className="space-y-4">
      <div className="alert alert-info">
        <span>JSX로 만든 엘리먼트와 React.createElement로 만든 엘리먼트는 같은 결과를 렌더링합니다.</span>
      </div>

      <div className="grid gap-4 md:grid-cols-2">
        <div className="rounded-box border border-base-300 bg-base-200 p-4">
          <p className="text-sm opacity-70 mb-2">JSX 방식</p>
          {el1}
        </div>

        <div className="rounded-box border border-base-300 bg-base-200 p-4">
          <p className="text-sm opacity-70 mb-2">React.createElement 방식</p>
          {el2}
        </div>
      </div>
    </div>
  );
}
