// -------------------------------------------------------------------------------------
// [1] Card 컴포넌트
// -------------------------------------------------------------------------------------
// - title은 일반 props다.
// - children은 <Card>와 </Card> 사이에 작성한 내용이다.
// -------------------------------------------------------------------------------------
function Card({ title, children }){
  return (
    <section>
      <h2>[{title}]</h2>
      <div>{children}</div>
    </section>
  );
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [2] Profile 대표 컴포넌트
// -------------------------------------------------------------------------------------
// - Profile은 부모 컴포넌트다.
// - Card는 자식 컴포넌트다.
// - Card 태그 사이의 p 요소들이 children으로 전달된다.
// -------------------------------------------------------------------------------------
export default function Profile(){
  return (
    <Card title="Profile">
      <p>Name: Yongsu</p>
      <p>Hello, React Learner!</p>
    </Card>
  );
}
// -------------------------------------------------------------------------------------

