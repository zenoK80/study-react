//----------------------------------------------------------------------------------
// 내용: 리스트 항목을 클릭했을 때 클릭된 과일 이름, 인덱스, 이벤트 객체를 콘솔에 출력한다.
//
// 배우고자 하는 것:
// - React에서는 onclick이 아니라 onClick처럼 camelCase로 이벤트를 작성한다.
// - onClick에는 문자열이 아니라 함수 참조를 넣는다.
// - map()으로 만든 리스트에서 item, index 값을 이벤트 핸들러로 전달한다.
// - React 이벤트 핸들러는 SyntheticEvent 객체를 받는다.
//----------------------------------------------------------------------------------
import React from "react";
const fruits = ["사과","바나나","체리"];

function FruitList(){
  function handleClick(item, index, event){
    console.log("클릭된 항목:", item);
    console.log("인덱스", index);
    console.log("SyntheticEvent 객체:", event);
  }

  return (
    <ul className="list-group">
      {fruits.map((item, index) => (
        <li onClick={(event) => handleClick(item, index, event)} key={item} className="list-group-item">{item}</li>
      ))}
    </ul>
  )
}

// ------------------------------------------------------------------------------------------
// [마무리 정리]
// ------------------------------------------------------------------------------------------
// event: 이벤트가 발생했을 때 React가 이벤트 핸들러 함수에 자동으로 넣어주는 이벤트 정보 객체
// - event.target: 실제로 클릭된 HTML 요소
// - event.type: 이벤트 종류, 예: "click"
// - event.clientX: 브라우저 화면 기준 클릭한 X 좌표
// - event.clientY: 브라우저 화면 기준 클릭한 Y 좌표
//
// map(): 배열을 돌면서 각 요소를 다른 형태로 바꿔서 새 배열을 만드는 함수
// - map(인자1, 인자2)
// - 인자1: 현재 반복 중인 배열의 요소
// - 인자2: 현재 반복 중인 요소의 순서 번호(index), 0부터 시작
//
// 예:
// fruits.map((item, index) => ...)
// - item: "사과", "바나나", "체리" 같은 현재 과일 이름
// - index: 0, 1, 2 같은 현재 순서 번호
// ------------------------------------------------------------------------------------------
