// -------------------------------------------------------------------------------------
// [React는 화면을 어떻게 그리고 바꿀까?]
// -------------------------------------------------------------------------------------
// 체크리스트
// - JSX는 브라우저가 이해하지 못하므로 BABEL이 번역한다
// - React Element는 실제 DOM이 아닌 UI 설계도 객체이다.
// - Virtual DOM은 전체 교체 대신 필요한 부분만 바꾸기 위한 구조다.
// - ReactDOM은 설계도를 실제 DOM에 반영하는 그림 도구다.
// - Fiber는 React가 상황에 따라 급한 업데이트를 먼저 처리할 수 있게 도와준다.
// - React는 UI를 담당하는 라이브러리이며, 실제 앱은 여러 도구르 조합해 완성한다.
// -------------------------------------------------------------------------------------
// React는 화면을 설계도(JSX)로 그리고, VirtualDom으로 달라진 부분만 똑똑하게 바꿔 주는 시스템이다.
// -------------------------------------------------------------------------------------
import { useState } from "react";

export default function ReactRendering(){
  const [count, setCount] =useState(0);
  const element = <p>현재 숫자: {count}</p>;
  console.log("React Element:",element);
  console.log("컴포넌트 렌더링");
  return (
    <section>
      {element}
      <button onClick={()=> setCount(count + 1)}>숫자 증가</button>
    </section>
  )
}
// -------------------------------------------------------------------------------------
// JSX 작성 -> React Element 객체 생성 -> React가 가상 화면 구조 계산 -> 이전 화면과 새로운 화면 비교 -> ReactDom이 변경 내용을 실제 DOM에 반영 -> 브라우저 변경
// -------------------------------------------------------------------------------------
// [Virtual DOM / ReactDOM / 실제 DOM 차이]
// -------------------------------------------------------------------------------------
// Virtual DOM:
// - React가 메모리에서 관리하는 가상의 화면 구조다.
// - JavaScript 객체 형태로 현재 UI 구조를 표현한다.
// - 이전 구조와 새로운 구조를 비교할 때 사용한다.
// - 브라우저 화면에 직접 보이는 실제 HTML 요소는 아니다.
// -------------------------------------------------------------------------------------
// ReactDOM:
// - React의 화면 구조를 브라우저의 실제 DOM에 반영하는 라이브러리다.
// - React와 웹 브라우저를 연결하는 역할을 한다.
// -------------------------------------------------------------------------------------
// 예:
// ReactDOM.createRoot(document.getElementById("root")).render(<App />);
// -------------------------------------------------------------------------------------
// DOM:
// - 브라우저가 HTML을 객체 구조로 표현한 것이다.
// - 실제 브라우저 화면과 연결되어 있다.
// - JavaScript의 document를 통해 직접 접근할 수 있다.
// -------------------------------------------------------------------------------------
// document:
// - 브라우저의 실제 DOM에 접근하기 위한 JavaScript 객체다.
// -------------------------------------------------------------------------------------
// 예:
// document.getElementById("root");
// -------------------------------------------------------------------------------------
// 차이점:
// - Virtual DOM: React 메모리 안의 가상 화면 구조
// - ReactDOM: React의 결과를 실제 DOM에 반영하는 도구
// - DOM: 브라우저가 관리하는 실제 화면 구조
// - document: 실제 DOM을 찾고 조작할 때 사용하는 객체
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [React가 주는 장점]
// -------------------------------------------------------------------------------------
// 1. 선언형 UI:
// - 개발자는 DOM 변경 순서를 직접 작성하지 않고 원하는 화면 결과를 JSX로 작성한다.
// - state가 변경되면 React가 새로운 화면을 계산하고 DOM에 반영한다.
// -------------------------------------------------------------------------------------
// 2. 상태와 화면의 동기화:
// - 화면에 사용하는 데이터를 state로 관리한다.
// - state가 변경되면 관련 컴포넌트가 다시 렌더링된다.
// - 데이터는 바뀌었지만 화면은 그대로인 실수를 줄일 수 있다.
// -------------------------------------------------------------------------------------
// 3. 컴포넌트 재사용:
// - 화면을 독립적인 컴포넌트로 나누어 관리할 수 있다.
// - 같은 컴포넌트를 여러 화면에서 재사용할 수 있다.
// - 한 컴포넌트를 수정하면 그 컴포넌트를 사용하는 화면에 함께 적용된다.
// -------------------------------------------------------------------------------------
// 4. 필요한 DOM 변경:
// - React는 이전 화면과 새로운 화면을 비교한다.
// - 비교 결과를 바탕으로 변경이 필요한 내용을 실제 DOM에 반영한다.
// - 개발자가 변경할 DOM 요소를 하나씩 직접 찾을 필요가 줄어든다.
// -------------------------------------------------------------------------------------
// 5. 유지보수:
// - UI, 상태, 이벤트 처리 코드를 컴포넌트 단위로 관리할 수 있다.
// - 화면이 복잡해져도 기능별로 코드를 나누어 확인할 수 있다.
// - 데이터가 화면에 전달되는 흐름을 비교적 쉽게 추적할 수 있다.
// -------------------------------------------------------------------------------------
// 6. 생태계:
// - 라우팅, 상태 관리, 데이터 요청 등 다양한 라이브러리와 함께 사용할 수 있다.
// - React는 UI를 담당하고 필요한 기능은 다른 도구와 조합하여 완성한다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [React는 무조건 빠른가?]
// -------------------------------------------------------------------------------------
// - React는 컴포넌트 실행, 화면 계산, 비교 과정이 추가된다.
// - 단순한 DOM 변경 하나만 보면 직접 DOM을 수정하는 방식이 더 빠를 수 있다.
// - React의 가장 큰 장점은 무조건적인 속도가 아니라 복잡한 UI의 관리와 유지보수다.
// - createRoot()는 상태가 변경될 때마다 실행하지 않고 앱을 시작할 때 보통 한 번 실행한다.
// - 이후에는 기존 React Root 안에서 필요한 화면 변경을 처리한다.
// -------------------------------------------------------------------------------------

