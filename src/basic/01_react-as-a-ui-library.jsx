// ------------------------------------------------------------------------------------------
// [import]
// - {} 안 쓰는 import: 파일에서 export default로 내보낸 걸 가져올 때 (default는 이 파일의 대표 1개)
// - {} 쓰는 import: 파일에서 이름 붙여서 내보낸 거 가져올 때 씀
// ------------------------------------------------------------------------------------------
import { useEffect, useState } from "react";
// ------------------------------------------------------------------------------------------

// ------------------------------------------------------------------------------------------
// [명령형 카운터]
// - useEffect(..., [])의 빈 배열: 언제 다시 실행할지 정하는 목록인데 [] 빈 배열이면 처음 화면에 나타난 뒤 딱 1번만 실행
// - 정리함수: useEffect 안에서 return으로 함수를 돌려주면 React가 그걸 기억해둠
// ------------------------------------------------------------------------------------------
function ImperativeCounter(){
  useEffect(()=>{
    const app = document.getElementById("imperative-counter");
    if( !app ) return;
    app.innerHTML = "";

    let count = 0;
    const button = document.createElement("button");
    button.textContent = "+1올리기";

    const display = document.createElement('p')
    display.textContent = "현재 카운트: 0";

    app.appendChild(button);
    app.appendChild(display);

    button.addEventListener("click", function () {
      count = count + 1;
      display.textContent = "현재 카운트: " + count;
    });

    return () => {
      app.innerHTML = "";
    };
  },[]);

  return <div id="imperative-counter"></div>;
}
// ------------------------------------------------------------------------------------------

// ------------------------------------------------------------------------------------------
// [선언형 카운터]
// ------------------------------------------------------------------------------------------
function DeclarativeCounter(){
  const [count, setCount] = useState(0);
  return(
    <div>
      <button onClick={() => setCount(count + 1)}>+1 올리기</button>
      <p>현재 카운트: {count}</p>
    </div>
  )
}
// ------------------------------------------------------------------------------------------

// ------------------------------------------------------------------------------------------
// [조립 메인 컴포넌트]
// ------------------------------------------------------------------------------------------
export default function ReactAsUiLibrary(){
  return(
    <div>
      <h3>명령형 카운터</h3>
      <ImperativeCounter></ImperativeCounter>
      <hr/>

      <h3>선언형 카운터</h3>
      <DeclarativeCounter></DeclarativeCounter>
    </div>
  )
}
// ------------------------------------------------------------------------------------------

