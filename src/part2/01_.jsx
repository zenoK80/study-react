// -------------------------------------------------------------------------------------
// [미션] 급식실 재고 관리 시스템
// -------------------------------------------------------------------------------------
// 내용:
// - useReducer로 급식실의 밥 재고를 관리한다.
// - 밥 하기를 누르면 10인분을 추가한다.
// - 배식하기를 누르면 1인분을 차감한다.
// - 재고는 0보다 작아질 수 없다.
//
// 배우고자 하는 것:
// - state: 현재 상태
// - action: 어떤 일이 발생했는지 나타내는 객체
// - dispatch: action을 reducer에 전달하는 함수
// - reducer: 현재 상태와 action을 받아 새로운 상태를 반환하는 함수
// -------------------------------------------------------------------------------------
import { useReducer } from "react";

// -------------------------------------------------------------------------------------
// [1] 초기
// 컴포넌트 초기 실행될 때 밥은 10인분
// -------------------------------------------------------------------------------------
const initialState = { rice: 10 };

// -------------------------------------------------------------------------------------
// [2] Reducer
// - state : 변경 전 상태
// - action : dispatch가 전달할 요청 객체
// - reducer는 기존 state를 직접 수정하지 않고 새로운 객체를 반환
// -------------------------------------------------------------------------------------
function cafeteriaReducer(state,action){
  switch (action.type) {
    case 'COOK_RICE': return { ...state, rice:state.rice + 10};
    case 'SERVE_RICE': if(state.rice <=0 ) return state; return { ...state, rice:state.rice - 1};
    default: return state;
  }
}

// -------------------------------------------------------------------------------------
// [3] Cafeteria 컴포넌트
// useReducer(reducer함수, 초기상태)
// state: 현재 상태
// dispatch: action을 reducer에 전달하는 함수
// -------------------------------------------------------------------------------------
export default function Cafeteria(){
  const [state,dispatch] = useReducer(cafeteriaReducer,initialState);

  function handleServeRice(){
    if(state.rice <= 0) {
      alert('남은 밥이 없습니다.');
      return;
    }
    dispatch( {type:"SERVE_RICE"} );
  }

  return(
    <section>
      <p>현재 밥 재고:{state.rice}인분</p>
      <button onClick={()=> dispatch({type:"COOK_RICE"})}>밥하기 +10</button>
      <button onClick={handleServeRice}></button>
    </section>
  );
}

// -------------------------------------------------------------------------------------
// [흐름 정리]
// -------------------------------------------------------------------------------------
// 버튼 클릭
// → dispatch(action)
// → cafeteriaReducer(state, action)
// → 새로운 state 반환
// → 컴포넌트 리렌더링
// → 화면의 재고 숫자 변경
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [마무리 정리]
// - dispatch({ type: "COOK_RICE" })는 action 객체를 reducer로 보낸다.
// - reducer는 action.type을 확인해서 새로운 state를 반환한다.
// - state가 변경되면 Cafeteria 컴포넌트가 다시 렌더링된다.
// - ...state는 기존 객체를 복사한다.
// - reducer는 상태 계산만 담당하므로 alert는 이벤트 함수에서 실행했다.
// -------------------------------------------------------------------------------------
