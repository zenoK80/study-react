// -------------------------------------------------------------------------------------
// [미션] TypeScript로 사용자 데이터 규격 만들기
// -------------------------------------------------------------------------------------
// - interface로 사용자 객체의 구조 정의한다
// - 컴포넌트가 받는 props의 타입을 정의한다
// - 잘못된 데이터가 들어오면 실행 전에 TypeScript 오류를 확인한다.
// -------------------------------------------------------------------------------------
// - interface: 객체가 가져야 할 속성과 타입을 정의한다.
// - : User: 값이 User 타입을 따라야 한다는 뜻이다.
// - Props 타입: 컴포넌트가 받을 데이터의 규칙이다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [1] User 인터페이스
// -------------------------------------------------------------------------------------
// - User 객체는 id와 displayName을 반드시 가져야한다.
// - id는 number, displayName은 string이어야 한다.
// -------------------------------------------------------------------------------------
interface User{
  id: number;
  displayName: string;
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [2] UserProfileProps 인터페이스
// -------------------------------------------------------------------------------------
// - UseProfile 컴포넌트가 받을 props의 구조
// - user에는 User 타입의 객체가 들어와야 한다.
// -------------------------------------------------------------------------------------
interface UserProfileProps{
  user: User;
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [3] UserProfile 컴포넌트
// -------------------------------------------------------------------------------------
// - { user }는 props에서 user 속성을 꺼내는 구조 분해 할당이다.
// - : UserProfileProps는 매개변수의 타입을 지정한다.
// -------------------------------------------------------------------------------------
function UserProfile({user}:UserProfileProps){
  return(
    <section>
      <h3>사용자 프로필</h3>
      <p>사용자 번호: {user.id}</p>
      <p>사용자 이름: {user.displayName.toUpperCase()}</p>
    </section>
  )
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [4] 대표 컴포넌트
// - currentUser 객체가 User 인터페이스를 따라야 한다.
// -------------------------------------------------------------------------------------
export default function TypeScriptPractice(){
  const currentUser: User = {
    id: 1004,
    displayName: "React with TypeScript",
  };

  return (
    <div>
      <h2>TypeScript Interface 실습</h2>
      <UserProfile user={currentUser} />
    </div>
  );
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [마무리 정리]
// - interface는 객체의 구조를 정의하는 TypeScript 문법이다. (객체 모양만 타입만 정의한다)
// - interface는 실행되는 JavaScript 코드가 아니라 검사할 때 사용하는 타입 정보다.
// - UserProfile은 User 타입의 객체만 user props로 받을 수 있다.
// - TypeScript는 잘못된 값을 브라우저 실행 전에 알려준다.
// -------------------------------------------------------------------------------------
