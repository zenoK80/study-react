// -------------------------------------------------------------------------------------
// [미션] 제네릭과 extends로 재사용 가능한 컴포넌트 만들기
// -------------------------------------------------------------------------------------
// - 제네릭을 사용하여 입력된 데이터의 타입을 그대로 유지한다.
// - extends로 데이터가 반드시 id를 가지도록 제한한다.
// - 하나의 DataList 컴포넌트로 사용자와 상품 목록을 모두 출력한다.
// -------------------------------------------------------------------------------------
// 배우고자 하는 것
// Generic: 사용하는 시점에 타입을 전달받는 문법
// T : 전달받은 타입을 임시로 나타내는 타입 변수
// extends : 제네릭 타입이 가져야 할 최소 조건
// any와 다르게 원래 데이터의 타입 정보를 유지하는 원리
// -------------------------------------------------------------------------------------
// ReactNode : 리액트가 화면에 그릴 수 있는 모든것을 의미하는 가장 넓은 범위의 타입
import type { ReactNode } from "react";

// -------------------------------------------------------------------------------------
// [1] 메타데이터 추가 제네릭 함수
// -------------------------------------------------------------------------------------
// - <T>는 함수가 호출될 때 결정되는 타입이다.
// - content의 타입을 T로 기억하고 반환 결과에도 그대로 유지한다.
// -------------------------------------------------------------------------------------
function wrapWithMetadata<T>(content: T){
  return {
    data: content,
    timestamp: Date.now(),
    id: Math.random().toString(36).substring(2, 9),
  };
}
// Math.random() : 0.123456789... 같은 무작위 소수를 만듭니다.
// toString() : 숫자를 글자로 바꾸는 함수.
// substring(시작위치,끝위치) : 문자열을 원하는 길이만큼 자르는 함수
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [2] DataListProps 재네릭 인터페이스
// -------------------------------------------------------------------------------------
// - T는 어떤 객체 타입이든 가능하다.
// - 단, id 속성은 반드시 string 또는 number 타입이어야 한다.
// - items는 T 타입 객체로 이루어진 배열이다.
// - renderRow는 T 타입 데이터를 받아 ReactNode를 반환하는 함수다.
// -------------------------------------------------------------------------------------
interface DataListProps<T extends {id:string|number}>{
  items:T[];
  renderRow:(item:T)=>ReactNode;
}

// -------------------------------------------------------------------------------------
// [3] DataList 제네릭 컴포넌트
// -------------------------------------------------------------------------------------
// - 데이터의 종류는 모르지만 모든 데이터에 id가 있다는 것은 보장된다.
// - renderRow를 호출하여 실제 출력 형태는 부모 컴포넌트가 결정한다.
// -------------------------------------------------------------------------------------
function DataList<T extends {id:string|number}>({items,renderRow}:DataListProps<T>){
  return(
    <ul>
    {items.map(item=>(<li key={item.id}>{renderRow(item)}</li>))}
    </ul>
  )
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [4] 사용자와 상품 타입
// -------------------------------------------------------------------------------------
interface User{
  id:number;
  displayName:string;
}
interface Product{
  id:string;
  title:string;
  price:number;
}
// -------------------------------------------------------------------------------------


// -------------------------------------------------------------------------------------
// [5]
// -------------------------------------------------------------------------------------
export default function GenericPractice(){
  const users:User[] = [
    {id:1,displayName:"Alice"},
    {id:2,displayName:"Bob"}
  ];

  const products: Product[] = [
    { id: "p1", title: "TypeScript 키보드", price: 150000 },
    { id: "p2", title: "설계 마우스", price: 89000 },
  ];

  const metadata = wrapWithMetadata({
    name: "React",
    category: "Library",
  });
  return (
    <section>
      <h2>TypeScript 제네릭 실습</h2>

      <h3>메타데이터</h3>
      <p>이름: {metadata.data.name}</p>
      <p>분류: {metadata.data.category}</p>
      <p>생성 시간: {metadata.timestamp}</p>

      <h3>사용자 목록</h3>
      <DataList<User> items={users}
        renderRow={user => (
          <span>{user.displayName} / ID: {user.id}</span>
        )}
      />

      <h3>상품 목록</h3>
      <DataList<Product> items={products}
        renderRow={product => (
          <span>{product.title} / {product.price.toLocaleString()}원</span>
        )}
      />
    </section>
  );
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [제네릭 문법 정리]
// -------------------------------------------------------------------------------------
// - <T>: 사용할 타입을 나중에 전달받기 위한 타입 변수
// - 함수명<T>(): 제네릭 함수 선언
// - DataList<User>: DataList의 T 자리에 User 타입 전달
// - T[]: T 타입 데이터로 구성된 배열
// - T extends { id: string | number }: T는 반드시 id 속성을 가져야 한다.
// - any는 타입 정보를 포기하지만 제네릭은 전달받은 타입을 계속 기억한다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [마무리 정리]
// -------------------------------------------------------------------------------------
// - 제네릭은 하나의 함수나 컴포넌트를 여러 타입에 재사용하게 해준다.
// - T는 실제 사용 시점에 전달받은 타입을 나타낸다.
// - extends는 제네릭에 최소한의 타입 조건을 설정한다.
// - DataList는 목록 구조를 담당하고 renderRow는 출력 내용을 담당한다.
// - 제네릭을 사용하면 재사용성과 타입 안전성을 함께 유지할 수 있다.
// -------------------------------------------------------------------------------------

