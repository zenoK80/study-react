// -------------------------------------------------------------------------------------
// [미션] TypeScript 타입을 React 컴포넌트에 적용하기
// -------------------------------------------------------------------------------------
// - props, state, 이벤트에 TypeScript 타입을 지정한다.
// - 구별된 공용체로 로딩, 성공, 에러 상태를 안전하게 표현한다.
// - ReactNode로 컴포넌트가 받을 children 타입을 지정한다.
// - Pick과 Omit으로 기존 타입에서 필요한 속성만 선택하거나 제거한다.
// -------------------------------------------------------------------------------------
// - 기본 타입: string, number, boolean
// - 선택적 속성: 값 뒤에 ?를 붙이면 생략할 수 있다.
// - 유니온 타입: 여러 타입 중 하나만 사용할 수 있다.
// - 타입 좁히기: 조건문으로 현재 타입을 구별한다.
// -------------------------------------------------------------------------------------
// [용어 정리]
// -------------------------------------------------------------------------------------
// - props: 부모 컴포넌트가 자식 컴포넌트에 전달하는 데이터
// - state: 컴포넌트가 내부에서 기억하며, 변경되면 화면을 다시 그리는 데이터
// - ReactNode: 문자열, 숫자, JSX 등 React가 화면에 출력할 수 있는 값의 타입
// - Pick: 기존 타입에서 필요한 속성만 선택해 새로운 타입 생성
// - Omit: 기존 타입에서 지정한 속성을 제외해 새로운 타입 생성
// - 선택적 속성(?): 있어도 되고 없어도 되는 속성
// - 유니온 타입(|): 여러 타입이나 값 중 하나를 허용하는 타입
// - 타입 좁히기: 조건문으로 현재 값의 정확한 타입을 구별하는 것
// -------------------------------------------------------------------------------------
// [React 타입 가져오기]
// -------------------------------------------------------------------------------------
// - import type: 실행할 값이 아니라 TypeScript 타입만 가져온다.
// - ChangeEvent: input 등의 값이 변경될 때 발생하는 이벤트 타입
// - ComponentPropsWithRef: button 같은 HTML 요소의 기본 props와 ref 타입
// - ReactNode: 문자열, 숫자, JSX 등 React가 화면에 출력할 수 있는 값의 타입
// -------------------------------------------------------------------------------------
// [여기까지 이해할 내용]
// -------------------------------------------------------------------------------------
// - TypeScript는 값이 어떤 타입인지 실행 전에 검사한다.
// - string, number, boolean은 TypeScript의 기본 타입이라 import하지 않는다.
// - ChangeEvent, ReactNode 등은 React가 만든 타입이라 react에서 가져온다.
// - useState는 실제로 실행하는 함수이므로 일반 import를 사용한다.
// - React 타입은 검사할 때만 필요하므로 import type을 사용한다.
// - import type으로 가져온 내용은 빌드된 JavaScript에서 제거된다.
// - {}는 해당 모듈이 이름을 붙여 export한 항목을 가져올 때 사용한다.
// - ref는 실제 DOM 요소를 가리킬 때 사용하는 React 기능이다.
// - ComponentPropsWithRef는 HTML 요소의 기본 props와 ref 타입을 제공한다.
// - 이벤트 객체: 이벤트가 발생했을 때 React가 함수에 전달하는 실제 데이터
// - 이벤트 타입: 이벤트 객체가 가진 속성을 TypeScript에 알려주는 규칙
// - ChangeEvent<HTMLInputElement>: input에서 발생한 값 변경 이벤트 타입
// - JavaScript는 타입을 미리 검사하지 않고 실행 중 전달된 이벤트 객체를 사용한다.
// - TypeScript는 실행 전에 검사하므로 이벤트가 발생한 요소와 종류를 알아야 한다.
// - JSX 안에 이벤트 함수를 바로 작성하면 TypeScript가 이벤트 타입을 추론할 수 있다.
// - 이벤트 함수를 따로 선언하면 매개변수 타입을 직접 지정해야 하는 경우가 많다.
// -------------------------------------------------------------------------------------
import { useState } from 'react';
import type {ChangeEvent, ComponentPropsWithRef, ReactNode,} from "react";

// -------------------------------------------------------------------------------------
// [1] User 인터페이스
// -------------------------------------------------------------------------------------
// - User 객체가 가져야 할 속성과 타입을 정의한다.
// - isVIP는 ?가 있으므로 생략할 수 있다.
// - interface는 실제 객체를 만들지 않고 타입 규칙만 만든다.
// -------------------------------------------------------------------------------------
interface User{
  name: string;
  age: number;
  isVIP?: boolean;
  email: string;
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [2] Pick으로 WelcomeProps 만들기
// -------------------------------------------------------------------------------------
// - Pick은 기존 타입에서 필요한 속성만 선택한다.
// - User에서 name, age, isVIP 속성만 가져온다.
// - email은 Welcome 컴포넌트에서 사용하지 않으므로 제외한다.
// -------------------------------------------------------------------------------------
type WelcomeProps = Pick<User, "name" | "age" | "isVIP">;
// -------------------------------------------------------------------------------------
// - <>: 타입에 필요한 다른 타입을 전달하는 제네릭 문법
// - Pick<User, 속성>: User 타입에서 지정한 속성만 선택
// - |: 또는(OR)를 뜻하며 여러 타입이나 값을 허용
// - "name" | "age": name 또는 age 속성을 선택한다는 뜻
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [3] Welcome 컴포넌트
// -------------------------------------------------------------------------------------
// - WelcomeProps 타입에 맞는 props만 받을 수 있다.
// - { name, age, isVIP } 는 props 객체에서 값을 꺼내는 구조 분해 할당이다.
// - isVIP가 true일 때만 VIP 문구를 출력한다.
// -------------------------------------------------------------------------------------
function Welcome({name, age, isVIP}:WelcomeProps){
  return(
    <section>
      <h3>사용자 정보</h3>
      <p>이름: {name}</p>
      <p>나이: {age}</p>
      {isVIP && <p>VIP 사용자입니다.</p>}
    </section>
  )
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [4] 구별된 공용체로 상태 타입 만들기
// -------------------------------------------------------------------------------------
// -state 속성으로 현재 상태가 loading, success, error중 무엇인지 구별
// -success 상태에서만 data를 사용할 수 있다.
// -error 상태에서만 error를 사용할 수 있다.
// -------------------------------------------------------------------------------------
type FetchStatus = {state: "loading"} | {state:"success"; data:string } | {state:"error"; error:Error};
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [type과 interface 차이]
// -------------------------------------------------------------------------------------
// - type: 객체, 기본 타입, 유니온 등 다양한 타입에 이름을 붙인다.
// - interface: 주로 객체가 가져야 할 속성과 타입을 정의한다.
// - 둘 다 객체 타입을 만들 수 있다.
// - 유니온 타입은 interface로 만들 수 없으므로 type을 사용한다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [5] StatusDisplay 컴포넌트
// -------------------------------------------------------------------------------------
// - status props는 FetchStatus 타입을 따라야 한다.
// - status.state를 검사하면 Typescript가 현재 상태의 타입을 좁힌다.
// - success에서는 data, error에서는 error를 사용할 수 있다.
// -------------------------------------------------------------------------------------
interface StatusDisplayProps{status: FetchStatus;}

function StatusDisplay({status}:StatusDisplayProps){
  if(status.state === 'loading') return <p>데이터 로딩중</p>
  if(status.state === 'success') return <p>성공: {status.data}</p>
  return <p>에러: {status.error.message}</p>
}
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [6] InputField 컴포넌트
// -------------------------------------------------------------------------------------
// - useState<string>은 text 상태에 문자열만 저장한다.
// - ChangeEvent<HTMLInputElement>는 input에서 발생한 변경 이벤트 타입
// - e.target.value에는 사용자가 입력한 문자열이 들어있음
// -------------------------------------------------------------------------------------
function InputField(){
  const [text, setText] = useState<string>("");

  function handleChange(e:ChangeEvent<HTMLInputElement>){
    setText(e.target.value);
  }

  return(
    <section>
      <h3>입력 이벤트 타입</h3>
      <input type="text" value={text} onChange={handleChange} placeholder="내용을 입력하세요" />
    </section>
  )
}
// -------------------------------------------------------------------------------------
// 제네릭: 함수나 타입을 만들 때, 사용할 타입을 나중에 <> 안으로 전달하는 방식
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [7] CustomButton 컴포넌트
// -------------------------------------------------------------------------------------
// - ComponentPropsWithRef<"button">은 HTML button의 기본 props 타입을 가져온다
// - Omit은 기본 button 타입에서 color와 children을 제외한다.
// - customColor는 "primary" 또는 "secondary"만 받을 수 있다.
// - ...rest에는 onClick, disabled 같은 나머지 button props가 들어간다.
// -------------------------------------------------------------------------------------
interface CustomButtonProps extends Omit<ComponentPropsWithRef<"button">, "color" | "children">{
  customColor: "primary" | "secondary";
  children: ReactNode;
}

function CustomButton({customColor, children, ...rest}:CustomButtonProps){
  return(
    <button {...rest} data-color={customColor}>
      {children}
    </button>
  )
}
// -------------------------------------------------------------------------------------
// [제네릭 구조 정리]
// -------------------------------------------------------------------------------------
// - ComponentPropsWithRef<"button">: HTML button이 사용할 수 있는 모든 props 타입
// - Omit<원본 타입, 제외할 속성>: 원본 타입에서 지정한 속성을 제거한다.
// - "color" | "children": color 또는 children 속성을 제외한다는 뜻이다.
// - extends: 가공한 button props 타입을 CustomButtonProps가 물려받는다.
// - customColor와 children은 이 interface 안에서 원하는 타입으로 다시 정의한다.
// - ...rest: customColor와 children을 제외한 나머지 props를 하나의 객체로 모은다.
// - {...rest}: 모은 onClick, disabled 등의 props를 실제 button에 전달한다.
// -------------------------------------------------------------------------------------

// -------------------------------------------------------------------------------------
// [8] 대표컴포넌트
// -------------------------------------------------------------------------------------
// - 앞에서 만든 컴포넌트에 실제 데이터 전달
// - FetchStatus 타입에 맞는 실제 객체 생성
// -------------------------------------------------------------------------------------
export default function TypeScriptPractice(){
  const loadingStatus: FetchStatus = { state: "loading"};
  const successStatus: FetchStatus = { state: "success", data:"데이터 불러오기 완료"}
  const errorStatus : FetchStatus = { state:"error", error: new Error("데이터를 불러오지 못했습니다.")}

  return(
    <div>
      <h2>TypeScript 타입 실습하기</h2>
      <Welcome name="zeno" age={99} isVIP />
      <StatusDisplay status={loadingStatus} />
      <StatusDisplay status={successStatus} />
      <StatusDisplay status={errorStatus} />

      <InputField />

      <CustomButton customColor="primary" onClick={() => alert("버튼을 클릭했습니다.")}>실행하기</CustomButton>

    </div>
  )
}

